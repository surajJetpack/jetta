#!/usr/bin/env node
/**
 * Refresh the vendored copy of the GetSign configuration reference
 * (lib/knowledge/getsign-reference-doc.ts) from the app team's repository.
 *
 *   node scripts/pull-getsign-reference.mjs            # from the dev branch
 *   node scripts/pull-getsign-reference.mjs --ref main
 *
 * Needs the GitHub CLI signed in to an account that can read the repository
 * (it is private). The daily kb-sync cron reads the reference itself when
 * JETTA_GETSIGN_REFERENCE_TOKEN is set, so this copy is the fallback and the
 * baseline the hand-written articles are pinned to. After a refresh,
 * scripts/getsign-reference-test.ts names the articles whose section changed:
 * correct them and their fingerprints in the same pull request.
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = "Jetpack-Work-Labs/getsign-board-view";
const PATH = "docs/agent/getsign-configuration-reference.md";
const refArg = process.argv.indexOf("--ref");
const ref = refArg > -1 ? process.argv[refArg + 1] : "dev";

const gh = (args) => execFileSync("gh", args, { encoding: "utf8", maxBuffer: 16 * 1024 * 1024 });

const markdown = gh(["api", `repos/${REPO}/contents/${PATH}?ref=${ref}`, "-H", "Accept: application/vnd.github.raw"]);
const [commit] = JSON.parse(gh(["api", `repos/${REPO}/commits?path=${PATH}&sha=${ref}&per_page=1`]));
if (!markdown.trim() || !commit?.sha) throw new Error("the reference or its last commit could not be read");

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "lib", "knowledge", "getsign-reference-doc.ts");
writeFileSync(
  out,
  [
    "// GENERATED by scripts/pull-getsign-reference.mjs. Do not edit by hand.",
    `// Source: ${REPO} ${PATH}`,
    "export const GETSIGN_REFERENCE = {",
    `  ref: ${JSON.stringify(ref)},`,
    `  commit: ${JSON.stringify(commit.sha)},`,
    `  committedAt: ${JSON.stringify(commit.commit.committer.date)},`,
    `  markdown: ${JSON.stringify(markdown)},`,
    "};",
    "",
  ].join("\n"),
);
console.log(`wrote ${out}\n${ref} @ ${commit.sha.slice(0, 7)} (${commit.commit.committer.date}), ${markdown.split("\n").length} lines`);
